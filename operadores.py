#operaciones matematicas
a = 7
b = 2

print(a+b) #suma
print(a-b) #resta
print(a*b) #multiplicacion
print(a/b) #division
print(a//b) #division entera, redondear el numero
print(a%b) #modulo, residuo de la division
print(a**b) #potencia, elevar a la potencia

print(a>b, a == b, a != b) #comparar dos valores, utiliza dos signo de igual. un signo de igual es para asignar un valor. 


